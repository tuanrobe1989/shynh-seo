<?php
/**
 * Robots.txt generator.
 *
 * @package Shynh_SEO
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

class Shynh_SEO_Robots_Txt {

	private static $instance = null;

	public static function get_instance() {
		if ( null === self::$instance ) {
			self::$instance = new self();
		}

		return self::$instance;
	}

	private function __construct() {
		add_filter( 'robots_txt', array( $this, 'render_robots_txt' ), 20, 2 );
		add_action( 'admin_init', array( $this, 'maybe_sync_physical_file' ), 30 );
		add_action( 'add_option_shynh_seo_settings', array( $this, 'sync_physical_file_on_save' ), 20, 2 );
		add_action( 'update_option_shynh_seo_settings', array( $this, 'sync_physical_file_on_save' ), 20, 3 );
	}

	public function render_robots_txt( $output, $public ) {
		$settings = Shynh_SEO_Core::get_settings();

		if ( empty( $settings['robots_txt_enabled'] ) ) {
			return $output;
		}

		return $this->build_content( $settings, $public );
	}

	public function sync_physical_file_on_save() {
		$settings = Shynh_SEO_Core::get_settings();

		$this->sync_physical_file_from_settings( $settings );
	}

	public function maybe_sync_physical_file() {
		if ( ! current_user_can( 'manage_options' ) ) {
			return;
		}

		$path = trailingslashit( ABSPATH ) . 'robots.txt';

		if ( file_exists( $path ) && ! $this->is_generated_file( $path ) ) {
			return;
		}

		$this->sync_physical_file_from_settings( Shynh_SEO_Core::get_settings() );
	}

	public function sync_physical_file_from_settings( $settings ) {
		$path     = trailingslashit( ABSPATH ) . 'robots.txt';

		if ( empty( $settings['robots_txt_enabled'] ) ) {
			$this->remove_generated_file( $path );
			return;
		}

		if ( file_exists( $path ) && ! $this->is_generated_file( $path ) ) {
			return;
		}

		$content = "# Generated by Shynh SEO\n" . $this->build_content( $settings, (bool) get_option( 'blog_public' ) );

		if ( ! function_exists( 'WP_Filesystem' ) ) {
			require_once ABSPATH . 'wp-admin/includes/file.php';
		}

		WP_Filesystem();
		global $wp_filesystem;

		if ( $wp_filesystem && $wp_filesystem->put_contents( $path, $content, FS_CHMOD_FILE ) ) {
			return;
		}

		if ( is_writable( dirname( $path ) ) || ( file_exists( $path ) && is_writable( $path ) ) ) {
			file_put_contents( $path, $content, LOCK_EX );
		}
	}

	private function build_content( $settings, $public ) {
		if ( ! $public ) {
			return $this->format_lines( array(
				'User-agent: *',
				'Disallow: /',
			) );
		}

		if ( 'manual' === ( $settings['robots_txt_mode'] ?? 'auto' ) ) {
			$manual_content = isset( $settings['robots_txt_manual_content'] ) ? trim( (string) $settings['robots_txt_manual_content'] ) : '';

			if ( '' !== $manual_content ) {
				return $this->sanitize_manual_content( $manual_content );
			}
		}

		$lines = Shynh_SEO_Core::get_default_robots_txt_lines( false );

		$custom_rules = isset( $settings['robots_txt_custom_rules'] ) ? trim( (string) $settings['robots_txt_custom_rules'] ) : '';
		if ( '' !== $custom_rules ) {
			$lines[] = '';
			$lines[] = '# Custom rules';
			foreach ( preg_split( '/\r\n|\r|\n/', $custom_rules ) as $rule ) {
				$rule = trim( wp_strip_all_tags( $rule ) );
				if ( '' !== $rule ) {
					$lines[] = $rule;
				}
			}
		}

		$lines[] = '';
		$lines[] = 'Sitemap: ' . home_url( '/sitemap.xml' );

		return $this->format_lines( apply_filters( 'shynh_seo_robots_txt_lines', $lines, $settings, $public ) );
	}

	private function is_generated_file( $path ) {
		if ( ! file_exists( $path ) || ! is_readable( $path ) ) {
			return false;
		}

		$contents = file_get_contents( $path, false, null, 0, 256 );

		return is_string( $contents ) && false !== strpos( $contents, 'Generated by Shynh SEO' );
	}

	private function remove_generated_file( $path ) {
		if ( $this->is_generated_file( $path ) && is_writable( $path ) ) {
			unlink( $path );
		}
	}

	private function format_lines( $lines ) {
		$lines = array_map( 'trim', (array) $lines );

		return implode( "\n", $lines ) . "\n";
	}

	private function sanitize_manual_content( $content ) {
		$lines = array();

		foreach ( preg_split( '/\r\n|\r|\n/', $content ) as $line ) {
			$line = trim( wp_strip_all_tags( $line ) );
			if ( '' === $line ) {
				$lines[] = '';
				continue;
			}

			$lines[] = $line;
		}

		return rtrim( implode( "\n", $lines ) ) . "\n";
	}
}
